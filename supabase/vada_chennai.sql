begin;
create table if not exists public.vada_pieces(slot text primary key check(slot ~ '^[a-h][78]$'), character_id text not null, png text not null check(length(png)<4000000 and png like 'data:image/png;base64,%'));
alter table public.vada_pieces enable row level security;
revoke all on public.vada_pieces from public,anon,authenticated;
grant select on public.vada_pieces to anon,authenticated;
grant insert,update on public.vada_pieces to authenticated;
drop policy if exists vc_read on public.vada_pieces;
create policy vc_read on public.vada_pieces for select using(true);
drop policy if exists vc_admin on public.vada_pieces;
create policy vc_admin on public.vada_pieces for all to authenticated using(public.is_admin()) with check(public.is_admin());
alter table public.vada_pieces drop constraint if exists vada_pieces_slot_check;
alter table public.vada_pieces add constraint vada_pieces_slot_check check(slot ~ '^[a-h][1278]$');
create table if not exists public.vada_music(id integer primary key check(id=1),name text not null,path text not null check(path ~ '^[a-f0-9-]+[.]mp3$'));
alter table public.vada_music enable row level security;
revoke all on public.vada_music from public,anon,authenticated;
grant select on public.vada_music to anon,authenticated;
grant insert,update on public.vada_music to authenticated;
drop policy if exists vc_music_read on public.vada_music;
create policy vc_music_read on public.vada_music for select using(true);
drop policy if exists vc_music_admin on public.vada_music;
create policy vc_music_admin on public.vada_music for all to authenticated using(public.is_admin()) with check(public.is_admin());
insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types) values('vada-bgm','vada-bgm',true,52428800,array['audio/mpeg']) on conflict(id) do nothing;
drop policy if exists vc_music_upload on storage.objects;
create policy vc_music_upload on storage.objects for insert to authenticated with check(bucket_id='vada-bgm' and public.is_admin());

drop policy if exists vc_guard_insert on storage.objects;
create policy vc_guard_insert on storage.objects as restrictive for insert to anon,authenticated  with check (bucket_id <> 'vada-bgm' or public.is_admin());
drop policy if exists vc_guard_update on storage.objects;
create policy vc_guard_update on storage.objects as restrictive for update to anon,authenticated using (bucket_id <> 'vada-bgm' or public.is_admin()) with check (bucket_id <> 'vada-bgm' or public.is_admin());
drop policy if exists vc_guard_delete on storage.objects;
create policy vc_guard_delete on storage.objects as restrictive for delete to anon,authenticated using (bucket_id <> 'vada-bgm' or public.is_admin());
commit;
